func TestGeneratedSource_PublicChecks(t *testing.T) {
	for _, tc := range generatedMarkerCases {
		t.Run(tc.name, func(t *testing.T) {
			src := "package testpkg\n"
			if tc.beforePkg {
				src = tc.prefix + src + generatedScanBody
			} else {
				// Constants must follow the import declaration.
				src += generatedScanBody + tc.prefix
				if tc.generated {
					src = "package testpkg\n" + tc.prefix +
						generatedScanBody
				}
			}
			dir := t.TempDir()
			// No generated filename convention is required.
			writeGo(t, dir, "ordinary.go", src)
			cfg := Config{
				Roots:                     []string{dir},
				RequirePointFreeBranching: true,
				RequireTrivialDelegate:    true,
				TerminalFunctions: []string{
					generatedTerminalName,
				},
			}
			for _, check := range generatedScanChecks {
				t.Run(check.name, func(t *testing.T) {
					vs, err := check.check(cfg)
					require.NoError(t, err)
					if tc.generated {
						require.Empty(t, vs)
						return
					}
					var functions []string
					for _, v := range vs {
						functions = append(functions, v.Function)
					}
					require.Contains(
						t,
						functions,
						check.wantFunc,
					)
				})
			}
		})
	}
}

func TestGeneratedSource_InvalidHandwrittenGo(t *testing.T) {
	dir := t.TempDir()
	writeGo(t, dir, "broken.go", "package testpkg\nfunc broken(")
	for _, check := range generatedScanChecks {
		t.Run(check.name, func(t *testing.T) {
			_, err := check.check(Config{
				Roots: []string{dir},
				TerminalFunctions: []string{
					generatedTerminalName,
				},
			})
			require.Error(t, err)
		})
	}
}

func TestGeneratedSource_MixedPackage(t *testing.T) {
	dir := t.TempDir()
	writeGo(t, dir, "support.go", `package testpkg
// Code generated by go generate; DO NOT EDIT.
const format = "plain"
func generatedTerminal(s string) int { return writeTerminal(s) }
`)
	writeGo(
		t,
		dir,
		"handwritten.go",
		"package testpkg\n"+strings.ReplaceAll(
			strings.ReplaceAll(generatedScanBody,
				`IO.Printf("plain")`, `IO.Printf(format)`),
			`return writeTerminal(s)`,
			`return generatedTerminal(s)`,
		),
	)
	for _, check := range generatedScanChecks {
		t.Run(check.name, func(t *testing.T) {
			vs, err := check.check(Config{
				Roots:                     []string{dir},
				RequireTrivialDelegate:    true,
				RequirePointFreeBranching: true,
				TerminalFunctions: []string{
					generatedTerminalName,
				},
			})
			require.NoError(t, err)
			var functions []string
			for _, v := range vs {
				require.Equal(t, "handwritten.go",
					filepath.Base(v.Position.Filename))
				functions = append(functions, v.Function)
			}
			require.Contains(t, functions, check.wantFunc)
		})
	}
}

func TestGeneratedSource_DelegateContext(t *testing.T) {
	cases := []struct {
		name      string
		generated string
		handmade  string
	}{
		{
			name:      "generated candidate excluded",
			generated: `func wrapper(s int) int { return step(s) }`,
		},
		{
			name:      "generated reference prevents single-use report",
			generated: `func reuse(s int) int { return wrapper(s) }`,
			handmade: `func wrapper(s int) int {
	return F.Pipe2(s, step, step)
}`,
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			dir := t.TempDir()
			writeGo(t, dir, "support.go", "package testpkg\n"+
				"// Code generated by go generate; DO NOT EDIT.\n"+
				tc.generated)
			writeGo(t, dir, "handwritten.go", `package testpkg
import F "github.com/IBM/fp-go/v2/function"
func use(s int) int { return F.Pipe1(s, wrapper) }
func step(s int) int { return s + 1 }
`+tc.handmade)
			cfg := Config{
				Roots:                  []string{dir},
				RequireTrivialDelegate: true,
			}
			for _, check := range []func(Config) ([]Violation, error){
				Check, CheckTrivialDelegate,
			} {
				vs, err := check(cfg)
				require.NoError(t, err)
				require.Empty(t, vs)
			}
		})
	}
}

func writeGo(t *testing.T, dir, name, src string) {
	t.Helper()
	require.NoError(t, os.WriteFile(
		filepath.Join(dir, name), []byte(src), 0o600,
	))
}
