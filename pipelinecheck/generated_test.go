// The lens constructor and optional getter use shapes from fp-go's
// generator. The other functions exercise each public scan with a
// known violation, so the generated-file cases cannot pass vacuously.
const generatedScanBody = `import (
	"fmt"
	"path/filepath"
	A "github.com/IBM/fp-go/v2/array"
	E "github.com/IBM/fp-go/v2/either"
	F "github.com/IBM/fp-go/v2/function"
	IO "github.com/IBM/fp-go/v2/io"
	IOE "github.com/IBM/fp-go/v2/ioeither"
	L "github.com/IBM/fp-go/v2/optics/lens"
	O "github.com/IBM/fp-go/v2/option"
)
type Person struct { Name string }
type PersonLenses struct { Name L.Lens[Person, string] }
func MakePersonLenses() PersonLenses {
	return PersonLenses{
		Name: L.MakeLens(
			func(s Person) string { return s.Name },
			func(s Person, v string) Person {
				s.Name = v
				return s
			},
		),
	}
}
func optionalName(s Person) O.Option[string] {
	return O.FromPredicate(func(v string) bool {
		return v != ""
	})(s.Name)
}
func runLens(s int) int { return F.Pipe1(s, delegate) }
func delegate(s int) int { return increment(s) }
func increment(s int) int { return s + 1 }
func bareBranch(s int) int {
	return F.Pipe1(s, func(n int) int {
		if n == 0 { return 1 }
		return n
	})
}
func loop(xs []int) int {
	for _, n := range xs { return n }
	return 0
}
func rawEffect(err error) IOE.IOEither[error, Person] {
	return IOE.TryCatchError(func() (Person, error) {
		if err != nil { return Person{}, fmt.Errorf("raw: %w", err) }
		return Person{}, nil
	})
}
func printValue(s string) IO.IO[string] {
	return IO.Printf("plain")(s)
}
func redundant(e E.Either[error, string]) error {
	return F.Pipe1(e, E.Fold(F.Identity[error],
		func(string) error { return nil }))
}
func joined(xs []string) []string {
	return F.Pipe1(xs, A.Map(func(s string) string {
		return filepath.Join("root", s)
	}))
}
func writeTerminal(s string) int { return len(s) }
func terminal(e E.Either[error, string]) int {
	return F.Pipe1(e, E.Fold(
		func(err error) int { return writeTerminal(err.Error()) },
		func(s string) int { return writeTerminal(s) },
	))
}
func local(s int) int {
	step := func(n int) int { return n + 1 }
	return F.Pipe1(s, step)
}
`

